export interface ServiceStyle {
  id: ServiceStyleId;
  title: string;
  subtitle: string;
  description: string;
  image: string;
  badge: string;
}

export interface MenuItem {
  id: string;
  name: string;
  malayalamName?: string;
  category: string;
  foodType: FoodTypeId;
  description?: string;
  serviceStyles?: ServiceStyleId[];
  isSignature?: boolean;
}

export interface MenuCategory {
  id: string;
  number: string;
  name: string;
  shortName: string;
  serviceStyles?: ServiceStyleId[];
  description?: string;
}

export interface PresetMenu {
  id: string;
  name: string;
  tagline: string;
  description: string;
  image: string;
  serviceStyle: ServiceStyleId;
  idealFor: string;
  itemIds: string[];
  suggestedCounters?: Array<{ name: string; itemIds: string[] }>;
}

export interface CateringCounter {
  id: string;
  name: string;
  itemIds: string[];
}

export interface EventDetails {
  fullName: string;
  phone: string;
  eventType: string;
  customEventType?: string;
  eventDate: string;
  guestCount: string;
  location: string;
  additionalNotes: string;
  preferredTime?: string;
  customRequestedDishes?: string;
}

